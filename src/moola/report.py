"""Regenerates results_summary.md and logs/equity.png from the logs. PROTECTED.

    python -m moola.report
"""
import json
from datetime import datetime, timezone

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from moola import logger
from moola.config import LOGS, ROOT, load_config
from moola.metrics import summarize

SUMMARY = ROOT / "results_summary.md"


def _pct(x) -> str:
    return "n/a" if x is None or pd.isna(x) else f"{x:.2%}"


def _window_row(name: str, eq: pd.DataFrame) -> str:
    if len(eq) < 2:
        return f"| {name} | n/a | n/a | n/a | n/a | n/a |"
    s = summarize(eq["equity"])
    bench = [eq[c].dropna() for c in ("bench_stock_close", "bench_crypto_close")]
    b = [(c.iloc[-1] / c.iloc[0] - 1) if len(c) > 1 else None for c in bench]
    return (f"| {name} | {_pct(s['total_return'])} | {s['sharpe']:.2f} | {_pct(s['max_drawdown'])} | "
            f"{_pct(b[0])} | {_pct(b[1])} |")


def _attribution(pos: pd.DataFrame) -> pd.Series:
    """Approximate P&L per symbol: yesterday's quantity x today's price change."""
    if pos.empty:
        return pd.Series(dtype=float)
    pos = pos.sort_values("date")
    pnl = {}
    for sym, g in pos.groupby("symbol"):
        g = g.set_index("date")
        pnl[sym] = float((g["qty"].shift(1) * g["current_price"].diff()).sum())
    return pd.Series(pnl).sort_values()


def write_summary(cfg: dict | None = None) -> None:
    cfg = cfg or load_config()
    eq = logger._read(logger.EQUITY)
    out = [f"# Moola results summary", "",
           f"_Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Auto-generated by `moola.report`, do not edit._", ""]
    if eq.empty:
        SUMMARY.write_text("\n".join(out + ["No live runs logged yet."]) + "\n")
        return

    eq["date"] = pd.to_datetime(eq["date"])
    eq = eq.set_index("date").sort_index()
    latest = eq.iloc[-1]
    out += [f"- **Strategy version:** {latest['strategy_version']}",
            f"- **Live since:** {eq.index[0]:%Y-%m-%d} ({len(eq)} runs)",
            f"- **Equity:** ${latest['equity']:,.2f} (cumulative P&L ${latest['cum_pnl']:,.2f})",
            f"- **Exposure:** gross {_pct(latest['gross_exposure'])}, crypto {_pct(latest['crypto_exposure'])}", "",
            "## Performance", "",
            "| window | return | Sharpe | max DD | SPY | BTC |", "|---|---|---|---|---|---|"]
    end = eq.index[-1]
    for name, days in (("last 7 days", 7), ("last 30 days", 30), ("since start", None)):
        out.append(_window_row(name, eq if days is None else eq[eq.index >= end - pd.Timedelta(days=days)]))

    out += ["", "## By strategy version", "", "| version | from | to | runs | return | Sharpe |", "|---|---|---|---|---|---|"]
    for v, g in eq.groupby((eq["strategy_version"] != eq["strategy_version"].shift()).cumsum()):
        s = summarize(g["equity"])
        out.append(f"| {g['strategy_version'].iloc[0]} | {g.index[0]:%Y-%m-%d} | {g.index[-1]:%Y-%m-%d} | {len(g)} | "
                   f"{_pct(s['total_return'])} | {s['sharpe']:.2f} |")

    pos = logger._read(logger.POSITIONS)
    if not pos.empty:
        now_pos = pos[pos["date"] == pos["date"].max()]
        out += ["", f"## Current positions ({pos['date'].max()})", "",
                "| symbol | market value | weight | unrealized P&L |", "|---|---|---|---|"]
        for _, p in now_pos.sort_values("market_value", ascending=False).iterrows():
            out.append(f"| {p['symbol']} | ${p['market_value']:,.0f} | {_pct(p['market_value'] / latest['equity'])} | "
                       f"${p['unrealized_pl']:,.0f} ({_pct(p['unrealized_plpc'])}) |")
        out += ["", "## Approximate P&L attribution since start", "", "| symbol | P&L |", "|---|---|"]
        out += [f"| {s} | ${v:,.0f} |" for s, v in _attribution(pos).items()]

    fills = logger._read(logger.FILLS)
    trades = logger._read(logger.TRADES)
    out += ["", "## Execution", "", f"- Orders submitted: {len(trades)}"]
    if not trades.empty and "error" in trades:
        out.append(f"- Orders rejected/errored: {int(trades['error'].notna().sum())}")
    if not fills.empty and "slippage_bps" in fills:
        out.append(f"- Fills: {len(fills)}, mean slippage {fills['slippage_bps'].mean():.1f} bps "
                   f"(worst {fills['slippage_bps'].max():.1f} bps)")

    flags, errors = [], []
    for path in sorted(logger.DAILY.glob("????-??-??.json"))[-14:]:
        d = json.loads(path.read_text())
        flags += [f"{d['date']}: {f}" for f in d.get("risk_flags", [])]
        errors += [f"{d['date']}: {k}: {v}" for k, v in d.get("errors", {}).items()]
    out += ["", "## Risk flags (last 14 runs)", ""] + ([f"- {f}" for f in flags] or ["None."])
    out += ["", "## Data/execution errors (last 14 runs)", ""] + ([f"- {e}" for e in errors] or ["None."])

    _chart(eq)
    out += ["", "![equity](logs/equity.png)", ""]
    SUMMARY.write_text("\n".join(out) + "\n")


def _chart(eq: pd.DataFrame) -> None:
    fig, ax = plt.subplots(figsize=(9, 4))
    (eq["equity"] / eq["equity"].iloc[0]).plot(ax=ax, label="Moola", linewidth=2)
    for col, label in (("bench_stock_close", "SPY"), ("bench_crypto_close", "BTC")):
        s = eq[col].dropna()
        if len(s) > 1:
            (s / s.iloc[0]).plot(ax=ax, label=label, alpha=0.6)
    ax.set_title("Growth of $1 since go-live")
    ax.legend()
    fig.tight_layout()
    fig.savefig(LOGS / "equity.png", dpi=110)
    plt.close(fig)


if __name__ == "__main__":
    write_summary()
    print(f"Wrote {SUMMARY}")
